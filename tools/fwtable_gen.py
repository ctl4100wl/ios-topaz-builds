#!/usr/bin/env python3
"""Generate TopazModem.cpp's firmware tables (fw_files, fw_ext, fw_all) from a modem
partition image (FAT16), so the driver matches this phone's modem_a instead of the
HyperOS 2.0.208 image the upstream tables were made from.

Usage: fwtable_gen.py modem_a.img OUT.inc [--check-dir MOUNTPOINT]
"""
import struct, sys, zlib, os


def parse(img):
    bps, spc, rsvd, nfats, nroot = struct.unpack_from('<HBHBH', img, 11)
    fatsz = struct.unpack_from('<H', img, 22)[0]
    assert fatsz, 'not FAT12/16'
    fat_off = rsvd * bps
    root_off = (rsvd + nfats * fatsz) * bps
    data_off = root_off + nroot * 32
    csize = spc * bps
    fat = img[fat_off:fat_off + fatsz * bps]

    def chain(c):
        out = []
        while 2 <= c < 0xfff8:
            out.append(c)
            c = struct.unpack_from('<H', fat, c * 2)[0]
        return out

    def entries(raw):
        for i in range(0, len(raw), 32):
            e = raw[i:i + 32]
            if e[0] == 0:
                return
            if e[0] == 0xe5 or e[11] == 0x0f or e[11] & 0x08:
                continue
            base = e[0:8].decode('ascii', 'replace').rstrip().lower()
            ext = e[8:11].decode('ascii', 'replace').rstrip().lower()
            if base in ('.', '..'):
                continue
            name = base + ('.' + ext if ext else '')
            clus = struct.unpack_from('<H', e, 26)[0]
            size = struct.unpack_from('<I', e, 28)[0]
            yield name, e[11], clus, size

    def dir_bytes(clus):
        return b''.join(img[data_off + (c - 2) * csize:data_off + (c - 1) * csize] for c in chain(clus))

    files = []

    def walk(raw, prefix):
        for name, attr, clus, size in entries(raw):
            path = prefix + name
            if attr & 0x10:
                walk(dir_bytes(clus), path + '/')
            else:
                ext = []
                left = size
                for c in chain(clus):
                    off = data_off + (c - 2) * csize
                    n = min(csize, left)
                    if n <= 0:
                        break
                    if ext and ext[-1][0] + ext[-1][1] == off and ext[-1][1] % csize == 0:
                        ext[-1][1] += n
                    else:
                        ext.append([off, n])
                    left -= n
                assert left <= 0 or size == 0, path
                files.append((path, size, ext))

    walk(img[root_off:data_off], '')
    return files


def main():
    img = open(sys.argv[1], 'rb').read()
    out = sys.argv[2]
    files = parse(img)
    lines = []
    modem = sorted(f for f in files if f[0].startswith('image/modem.'))
    lines.append('static const struct { const char *name; uint32_t off, size, crc; } fw_files[] = {')
    for path, size, ext in modem:
        assert len(ext) == 1, f'{path} is fragmented'
        off = ext[0][0]
        crc = zlib.crc32(img[off:off + size]) & 0xffffffff
        lines.append(f'\t{{ "{path[6:]}", {off:#x}, {size:#x}, {crc:#010x} }},')
    lines.append('};')
    allx, allf = [], []
    for path, size, ext in files:
        allf.append(f'\t{{ "{path}", {size:#x}, {len(allx)}, {len(ext)} }},')
        allx += [f'\t{{ {o:#x}, {n:#x} }},' for o, n in ext]
    lines.append(f'/* generated by fwtable_gen.py from this phone\'s modem_a: {len(files)} files, {len(allx)} extents */')
    lines.append('static const struct { uint32_t off, len; } fw_ext[] = {')
    lines += allx
    lines.append('};')
    lines.append('static const struct { const char *path; uint32_t size; uint16_t ext, next; } fw_all[] = {')
    lines += allf
    lines.append('};')
    open(out, 'w').write('\n'.join(lines) + '\n')
    print(f'{len(modem)} modem files, {len(files)} files, {len(allx)} extents')

    if '--check-dir' in sys.argv:
        root = sys.argv[sys.argv.index('--check-dir') + 1]
        bad = 0
        for path, size, ext in files:
            data = b''.join(img[o:o + n] for o, n in ext)
            ref = open(os.path.join(root, path), 'rb').read()
            if data != ref:
                bad += 1
                print('MISMATCH', path)
        print(f'checked {len(files)} files against {root}: {bad} mismatches')


if __name__ == '__main__':
    main()
